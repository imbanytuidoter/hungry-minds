// Generates contract/src/glossy_parts.rs from the site's own shape module
// (web/lib/game/glossyParts.ts), so the NFT image drawn on chain matches the game.
//   node web/scripts/gen-glossy-rs.mjs        (Node 22.6+/24: imports the .ts directly)

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { BODY, eyes, hats, outfits } from "../lib/game/glossyParts.ts";

const rsStr = (s) => JSON.stringify(s); // Rust string literals accept the same escapes here
const part = (z) => `P { d: ${rsStr(z.d)}, fill: ${rsStr(z.f)}, stroke: ${rsStr(z.s)}, width: ${rsStr(String(z.w))} }`;
const table = (name, fn) =>
  `pub const ${name}: [&[P]; 11] = [\n` +
  Array.from({ length: 11 }, (_, i) => `    &[${fn(i).map(part).join(", ")}],`).join("\n") +
  `\n];\n`;

const out =
  `// GENERATED by web/scripts/gen-glossy-rs.mjs from web/lib/game/glossyParts.ts — do not edit.\n` +
  `// The glossy character's eyes, hats and outfits, so the NFT drawn on chain matches the game.\n\n` +
  `/// One SVG path: d, fill, stroke, stroke-width.\npub struct P {\n    pub d: &'static str,\n    pub fill: &'static str,\n    pub stroke: &'static str,\n    pub width: &'static str,\n}\n\n` +
  `/// The body outline; outfits are clipped to it.\npub const BODY: &str = ${rsStr(BODY)};\n\n` +
  table("EYES", eyes) +
  "\n" +
  table("HATS", hats) +
  "\n" +
  table("OUTFITS", outfits);

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "..", "contract", "src", "glossy_parts.rs");
writeFileSync(target, out);
console.log("wrote", target, out.length, "bytes");
